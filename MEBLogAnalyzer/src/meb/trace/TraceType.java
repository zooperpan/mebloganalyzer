package meb.trace;

/**
 * An enumeration declaring the type of an object extending the {@link BaseTrace}.
 * @author Panos Katsikogiannis
 *
 */
public enum TraceType {
	/**
	 * Used for the {@link MessageTrace} type.
	 */
	MESSAGE,

	/**
	 * Used for the {@link StateTrace} type.
	 */
	STATE,

	/**
	 * Used for the {@link InfoTrace} type.
	 */
	INFO,
}
